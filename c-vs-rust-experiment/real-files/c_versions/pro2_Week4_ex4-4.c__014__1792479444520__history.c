#include <stdio.h>

int main(void){
    int a[2][2];
    int n,i,j;
    int p[2][2];
    int t[2][2];
    p[0][0]=1;
    p[0][1]=0;
    p[1][0]=0;
    p[1][1]=1;
    
    printf("行列aを入力してください\n");
    printf("a[0][0]=");
    scanf("%d",&a[0][0]);
    printf("a[0][1]=");
    scanf("%d",&a[0][1]);
    printf("a[1][0]=");
    scanf("%d",&a[1][0]);
    printf("a[1][1]=");
    scanf("%d",&a[1][1]);
    printf("何乗しますか:");
    scanf("%d",&n);
    for(i=0;i<n;i++){
    t[0][0]=p[0][0];
    t[0][1]=p[0][1];
    t[1][0]=p[1][0];
    t[1][1]=p[1][1];
    p[0][0]=t[0][0]*a[0][0]+t[0][1]*a[1][0];
    p[0][1]=t[0][0]*a[0][1]+t[0][1]*a[1][1];
    p[1][0]=t[1][0]*a[0][0]+t[1][1]*a[1][0];
    p[1][1]=t[1][0]*a[0][1]+t[1][1]*a[1][1];
    }

    printf("行列aの%d乗は",n);
    printf("p[0][0]=%d\n",p[0][0]);
    printf("p[0][1]=%d\n",p[0][1]);
    printf("p[1][0]=%d\n",p[1][0]);
    printf("p[1][1]=%d\n",p[1][1]);
}
